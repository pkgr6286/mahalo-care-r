async function request(path:string,body?:unknown,status=200){
  const res=await fetch(base+path,{method:body?"POST":"GET",headers:{"content-type":"application/json",...(cookie?{cookie}:{})},body:body?JSON.stringify(body):undefined});
  assert.equal(res.status,status,`${path}: ${await res.clone().text()}`);
  if(path==="/auth/login"&&res.ok)cookie=res.headers.get("set-cookie")!.split(";")[0]!;
  checks++;
  return res.json();
}
