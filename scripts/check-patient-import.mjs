import assert from "node:assert/strict";
import { csvSheet, guessColumns, mappedRows, mappedCsv, checkedSheet } from "../artifacts/mahalo-care/src/lib/patient-import.ts";
const sheet = csvSheet('\ufeffFirst Name,Last Name,Date of Birth,Clinic,MRN,Extra\r\nAlex,"Example, Jr",1960-05-14,Garden City,000123,ignore\r\n');
const original = JSON.stringify(sheet);
const mapping = guessColumns(sheet);
assert.deepEqual(mapping, { firstName: 0, lastName: 1, dob: 2, location: 3, mrn: 4 });
assert.equal(mappedRows(sheet, mapping, {})[0].mrn, "000123");
assert.equal(mappedRows(sheet, mapping, {})[0].lastName, "Example, Jr");
assert(!mappedCsv(sheet, mapping, {}).includes("ignore"));
assert.equal(csvSheet(mappedCsv(sheet, mapping, {})).rows.length, 2);
assert.throws(() => mappedRows(sheet, { ...mapping, lastName: 0 }, {}), /only one/);
assert.throws(() => mappedRows(sheet, { firstName: 0 }, {}), /last name/);
const excel = { name: "Patients", rows: [["First name", "Last name", "DOB"], ["Alex", "Example", new Date("1960-05-14T00:00:00Z")]] };
const excelMap = guessColumns(excel);
assert.equal(mappedRows(excel, excelMap, { location: "Garden City" })[0].dob, "1960-05-14");
assert.equal(mappedRows(excel, excelMap, { location: "Garden City" })[0].location, "Garden City");
assert.throws(() => checkedSheet({ name: "Empty", rows: [["First name"]] }), /at least one/);
assert.throws(() => checkedSheet({ name: "Large", rows: Array.from({ length: 502 }, () => ["A"]) }), /500/);
assert.throws(() => csvSheet('A,B\n"unterminated,B'), /Quote|quote/);
assert.equal(checkedSheet({ name: "Blanks", rows: [[null], ["First name"], [null], ["Alex"]] }).rows.length, 2);
assert.throws(() => mappedCsv({ name: "Oversized", rows: [["First name","Last name","DOB","Site"], ["A".repeat(300_001), "B", "1960-05-14", "Garden City"]] }, { firstName: 0, lastName: 1, dob: 2, location: 3 }, {}), /300 KB/);
assert.equal(JSON.stringify(sheet), original, "Matching and CSV conversion must not mutate the source roster.");
console.log("Patient import parsing, matching, dates, defaults, escaping and size checks passed.");
