import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
const require = createRequire(new URL("../artifacts/api-server/package.json", import.meta.url));
const ExcelJS = require("exceljs");
const suffix = randomUUID().slice(0, 8);
const workbook = new ExcelJS.Workbook();
workbook.addWorksheet("Instructions").addRow(["Fictional training roster. Import the Patients worksheet."]);
const patients = workbook.addWorksheet("Patients");
patients.addRow(["First Name", "Last Name", "Date of Birth", "Clinic", "Medical Record Number", "Email"]);
patients.addRow(["Alex", `Example-${suffix}`, new Date("1960-05-14T00:00:00Z"), "Garden City", `0007-${suffix}`, `alex.${suffix}@example.test`]);
patients.addRow(["Robin", `Example-${suffix}`, new Date("1954-09-23T00:00:00Z"), "Garden City", `0008-${suffix}`, `robin.${suffix}@example.test`]);
patients.getColumn(3).numFmt = "yyyy-mm-dd";
patients.getColumn(5).numFmt = "@";
await mkdir("generated-artifacts", { recursive: true });
await workbook.xlsx.writeFile("generated-artifacts/patient-import-test.xlsx");
await writeFile("generated-artifacts/patient-import-invalid.csv", `First Name,Last Name,Date of Birth,Clinic\nAlex,Invalid-${suffix},1960-02-30,Garden City\n`);
await writeFile("generated-artifacts/patient-import-test.json", JSON.stringify({ suffix, lastName: `Example-${suffix}`, firstMrn: `0007-${suffix}`, secondMrn: `0008-${suffix}` }));
console.log(`Created two-row fictional workbook for browser verification: Example-${suffix}.`);
